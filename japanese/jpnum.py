"""Чтения японских чисел, дат и времени по правилам с исключениями.

Сборщик сверяет каждое чтение со статьями JMdict, где такие статьи есть (一日 ついたち,
二十日 はつか, 四月 しがつ, 三百 さんびゃく и т.д.), расхождение валит сборку.
"""
DIG = {0: "ゼロ", 1: "いち", 2: "に", 3: "さん", 4: "よん", 5: "ご", 6: "ろく", 7: "なな", 8: "はち", 9: "きゅう"}
HUNDRED = {1: "ひゃく", 2: "にひゃく", 3: "さんびゃく", 4: "よんひゃく", 5: "ごひゃく",
           6: "ろっぴゃく", 7: "ななひゃく", 8: "はっぴゃく", 9: "きゅうひゃく"}
THOUSAND = {1: "せん", 2: "にせん", 3: "さんぜん", 4: "よんせん", 5: "ごせん",
            6: "ろくせん", 7: "ななせん", 8: "はっせん", 9: "きゅうせん"}
MONTH = {1: "いちがつ", 2: "にがつ", 3: "さんがつ", 4: "しがつ", 5: "ごがつ", 6: "ろくがつ", 7: "しちがつ",
         8: "はちがつ", 9: "くがつ", 10: "じゅうがつ", 11: "じゅういちがつ", 12: "じゅうにがつ"}
DAY_SPECIAL = {1: "ついたち", 2: "ふつか", 3: "みっか", 4: "よっか", 5: "いつか", 6: "むいか", 7: "なのか",
               8: "ようか", 9: "ここのか", 10: "とおか", 14: "じゅうよっか", 20: "はつか", 24: "にじゅうよっか"}
DAY_UNIT = {1: "いち", 2: "に", 3: "さん", 5: "ご", 6: "ろく", 7: "しち", 8: "はち", 9: "く"}  # 17 じゅうしち, 19 じゅうく
WEEKDAY = [("月曜日", "げつようび", "понедельник"), ("火曜日", "かようび", "вторник"), ("水曜日", "すいようび", "среда"),
           ("木曜日", "もくようび", "четверг"), ("金曜日", "きんようび", "пятница"), ("土曜日", "どようび", "суббота"),
           ("日曜日", "にちようび", "воскресенье")]
HOUR = {1: "いちじ", 2: "にじ", 3: "さんじ", 4: "よじ", 5: "ごじ", 6: "ろくじ", 7: "しちじ", 8: "はちじ", 9: "くじ",
        10: "じゅうじ", 11: "じゅういちじ", 12: "じゅうにじ"}
MINUTE = {1: "いっぷん", 2: "にふん", 3: "さんぷん", 4: "よんぷん", 5: "ごふん", 6: "ろっぷん", 7: "ななふん",
          8: "はっぷん", 9: "きゅうふん", 10: "じゅっぷん"}
MONTH_RU = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября",
            "ноября", "декабря"]


def number(n):
    """0..99999999 -> чтение хираганой (ゼロ катаканой)."""
    if n == 0:
        return DIG[0]
    out = ""
    man, n = divmod(n, 10000)
    if man:
        out += number(man) + "まん"
    th, n = divmod(n, 1000)
    if th:
        out += THOUSAND[th]
    hu, n = divmod(n, 100)
    if hu:
        out += HUNDRED[hu]
    te, n = divmod(n, 10)
    if te:
        out += ("" if te == 1 else DIG[te]) + "じゅう"
    if n:
        out += DIG[n]
    return out


def month(m):
    return MONTH[m]


def day(d):
    if d in DAY_SPECIAL:
        return DAY_SPECIAL[d]
    te, u = divmod(d, 10)
    head = ("" if te == 1 else DIG[te]) + "じゅう" if te else ""
    return head + DAY_UNIT[u] + "にち" if u else head + "にち"


def minute(m):
    if m == 0:
        return ""
    if m == 30:
        return "はん"
    te, u = divmod(m, 10)
    if u == 0:
        return ("" if te == 1 else DIG[te]) + "じゅっぷん"
    return (("" if te == 1 else DIG[te]) + "じゅう" if te else "") + MINUTE[u]


def time(h, m):
    return HOUR[h] + minute(m)


def year(y):
    tail = y % 10
    base = number(y - tail)
    return base + {4: "よねん", 7: "ななねん", 9: "きゅうねん"}.get(tail, number(tail) + "ねん" if tail else "ねん")


def date_written(m, d):
    return f"{m}月{d}日"


def date_reading(m, d):
    return f"{month(m)} {day(d)}"


def date_ru(m, d):
    return f"{d} {MONTH_RU[m - 1]}"
